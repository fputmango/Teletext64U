// Spanish national option subset (ETS 300 706, table 36): these characters replace ASCII characters. More info:
// https://www.etsi.org/deliver/etsi_i_ets/300700_300799/300706/01_60/ets_300706e01p.pdf
var atrSpanishSubset = map[rune]byte{
	'ç': 0x23, '¡': 0x40, 'á': 0x5B, 'é': 0x5C, 'í': 0x5D, 'ó': 0x5E, 'ú': 0x5F, '¿': 0x60, 'ü': 0x7B, 'ñ': 0x7C, 'è': 0x7D, 'à': 0x7E,
	// Some pages are drawn with the German character set instead of the Spanish one, so the broadcaster's 'á' and
	// 'ó' appear as 'Ä' and '^' ("MÄs informaci^n"). Mapping them back to their byte gives the intended letter.
	'Ä': 0x5B, '^': 0x5E,
}

// Characters outside the subset are sent as ISO-8859-1 (like the other services do). The client (map_extended_ascii_to_txt_charset(), Spanish part)
// maps each of these bytes to a slot of the Spanish G2 bank (teletext-bold-sp-g2.bin / teletext-thin-sp-g2.bin, release 2.10.0 and later).
// Every byte listed here must be known to the client, or it will show a wrong character.
var atrLatin1 = map[rune]byte{
	'Á': 0xC1, 'É': 0xC9, 'Í': 0xCD, 'Ó': 0xD3, 'Ú': 0xDA, 'Ñ': 0xD1, 'Ç': 0xC7, 'Ü': 0xDC,
	'º': 0xBA, 'ª': 0xAA, '°': 0xB0,
	'€': 0x80, // the client has the euro in the same slot of the default G2 and the Spanish bank
	'@': 0xA4, // 0x40 is ¡ in the Spanish subset, so the '@' gets its own byte
}

// These characters can't be shown. They are mapped to something similar.
var atrReplacements = map[rune]byte{
	// Polish and other letters from tlgzGlyphArt
	'Ą': 'A', 'Ć': 'C', 'Ę': 'E', 'Ł': 'L', 'Ń': 'N', 'Ś': 'S', 'Ź': 'Z', 'Ż': 'Z', 'Č': 'C',
	'ą': 'a', 'ć': 'c', 'ę': 'e', 'ł': 'l', 'ń': 'n', 'ś': 's', 'ź': 'z', 'ż': 'z', 'č': 'c', 'ř': 'r', 'ş': 's',
	// Not in the Spanish G2 bank (not seen on the pages so far); these bytes would otherwise end up in the wrong slot on the client
	'Ö': 'O', 'ö': 'o', 'ê': 'e', 'å': 'a', 'ò': 'o', 'î': 'i', 'ì': 'i', 'ß': 's',
	'’': '\'', '‘': '\'', '×': 'x', '§': 'S', '¦': '/', '―': '-', '♪': '*',
	'■': 0x7F, // shown as a block in text mode
	// ASCII characters whose position holds a Spanish letter
	'#': '*', '_': '-',
}

func atrRuneToByte(r rune) byte {
	if b, ok := atrSpanishSubset[r]; ok {
		return b
	}
	if b, ok := atrLatin1[r]; ok {
		return b
	}
	if b, ok := atrReplacements[r]; ok {
		return b
	}
	if r >= 0x20 && r < 0x7F {
		return byte(r)
	}
	return '?'
}
