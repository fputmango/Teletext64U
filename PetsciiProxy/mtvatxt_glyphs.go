func mtvaTxtRuneToByte(r rune) byte {
	// ISO-8859-2 positions of the letters that differ from ISO-8859-1
	switch r {
	case 'ő':
		r = 0xF5
	case 'Ő':
		r = 0xD5
	case 'ű':
		r = 0xFB
	case 'Ű':
		r = 0xDB
	}
	if r < 0x80 {
		return byte(r)
	}
	if r <= 0xFF {
		if b, ok := mtvaTxtAccentStrip[byte(r)]; ok {
			return b
		}
	}
	switch r {
	case 'ä', 'å':
		return 'a'
	case 'Ä', 'Å':
		return 'A'
	case '¤':
		return '$'
	case '’':
		return '\''
	}
	return '?'
}
