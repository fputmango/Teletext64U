// Glyph table for mtvatxt.go
//
// teletext.hu uses GIF images for displaying teletext pages. Each character is 13x16 pixels. This table holds a 'picture' of each character.
//
// How does it work?
// - At startup every picture is turned into a key of 16 numbers (one for each pixel line)
// - The decoder turns every two-colour cell of a GIF into a similair key, trying each of the two colours as the foreground, and looks it up. Only an exact match counts.
// - Double height characters are read over two rows, taking every other pixel line, which gives back the normal size shape.
// - NOTE: there is no need to add mosaics; they will be recognised from their block shape.
//
// Adding new chars: When the decoder sees a cell it doesn't recognise, it logs the cell once, in the format below, with '?' as the character.
// If it is indeed a character then copy the entry into the table below and replace ? by the character.
//
// Copyright (C) 2026 Frank Putman
