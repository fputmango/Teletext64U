// Characters from the Polish national option subset (ETS 300 706, table 36) and the byte that shows them on the client, with the country set to Polish
// https://www.etsi.org/deliver/etsi_i_ets/300700_300799/300706/01_60/ets_300706e01p.pdf page 115
var tlgzPolishSubset = map[rune]byte{
	'#': 0x23, 'ń': 0x24, 'ą': 0x40, 'Ż': 0x5B, 'Ś': 0x5C, 'Ł': 0x5D, 'ć': 0x5E, 'ó': 0x5F, 'ę': 0x60, 'ż': 0x7B, 'ś': 0x7C, 'ł': 0x7D, 'ź': 0x7E,
}

// These characters aren't in the Polish subset. They are mapped to a basic letter.
var tlgzReplacements = map[rune]byte{
	'Ą': 'A', 'Ć': 'C', 'Ę': 'E', 'Ń': 'N', 'Ó': 'O', 'Ź': 'Z',
	'á': 'a', 'é': 'e', 'í': 'i', 'ö': 'o', 'ü': 'u', 'ç': 'c', 'ş': 's', 'ř': 'r', 'č': 'c',
	'Ö': 'O', 'Ç': 'C', 'Č': 'C',
	'’': '\'', '‘': '\'', '×': 'x', '§': 'S',
	'■': 0x7F, // shown as a block in text mode
	// ASCII characters whose position holds a Polish letter
	'@': '*', '_': '-',
}

func tlgzRuneToByte(r rune) byte {
	if b, ok := tlgzPolishSubset[r]; ok {
		return b
	}
	if b, ok := tlgzReplacements[r]; ok {
		return b
	}
	if r >= 0x20 && r < 0x7F {
		return byte(r)
	}
	return '?'
}
