// Glyph table for telegazeta.go
//
// Telegazeta uses PNG images for displaying teletext. Each character is 12x14 pixels. This table holds a 'picture' of each character.
//
// How does it work?
// - At startup every picture is turned into a key of 14 numbers (one for each pixel line)
// - The decoder turns every two-colour cell of a PNG into a similar key, trying each of the two colours as the foreground, and looks it up. Only an exact match counts.
// - Double height, double width and double size characters are read over two rows and/or two columns, taking every other pixel line/column, which gives back the normal size shape.
// - NOTE: there is no need to add mosaics; they will be recognised from their block shape.
//
// Adding new chars: When the decoder sees a cell it doesn't recognise, it logs the cell once, in the format below, with '?' as the character.
// If it is indeed a character then copy the entry into the table below and replace ? by the character.
//
// Copyright (C) 2026 Frank Putman
// SPDX-License-Identifier: GPL-3.0-or-later

